def test_golden_frame_regenerates_from_the_bag(golden_pair: FramePair, segmenter):
    record = _golden_record(golden_pair, segmenter)
    if os.environ.get("NAZEER_WRITE_GOLDEN") == "1":
        GOLDEN_JSON.parent.mkdir(parents=True, exist_ok=True)
        text = json.dumps(jsonsafe.to_finite(record), ensure_ascii=False, indent=2, allow_nan=False)
        GOLDEN_JSON.write_text(text + "\n", encoding="utf-8")
    golden = json.loads(GOLDEN_JSON.read_text(encoding="utf-8"))

    # the reader: the same pair, the same bytes (rgb8 -> BGR once; depth aligned to colour)
    rf, gf = record["frame"], golden["frame"]
    for key in ("read_index", "frame_number_color", "frame_number_depth", "shape"):
        assert rf[key] == gf[key], key
    assert rf["color_timestamp_ms"] == pytest.approx(gf["color_timestamp_ms"], abs=1e-3)
    assert rf["bgr_sha256"] == gf["bgr_sha256"], "colour bytes changed (RGB->BGR conversion?)"
    assert rf["depth_m_float32_sha256"] == gf["depth_m_float32_sha256"], "aligned depth changed"
    for key in ("fx", "fy", "cx", "cy", "width", "height"):
        assert rf["intrinsics"][key] == pytest.approx(gf["intrinsics"][key], abs=1e-6), key

    # the model contract, with the CLAUDE.md tolerances
    rm, gm = record["model"], golden["model"]
    tol = gm["tolerances"]
    assert rm["sha256"] == gm["sha256"] == MODEL_SHA256_PINNED
    assert abs(rm["conf"] - gm["conf"]) <= tol["conf_abs"]
    assert abs(rm["mask_px"] - gm["mask_px"]) <= tol["mask_px_frac"] * gm["mask_px"]
    for got, want in zip(rm["mask_rows"], gm["mask_rows"], strict=True):
        assert abs(got - want) <= tol["rows_px"]

    # the frozen frame block: eroded-mask median Z_ref, depth-valid bbox, near-plane ground row
    rz, gz = record["z_ref"], golden["z_ref"]
    assert rz["statistic"] == "median" and rz["erosion_fallback"] is False
    assert abs(rz["z_ref_m"] - gz["z_ref_m"]) <= 0.005
    assert abs(rz["n_valid"] - gz["n_valid"]) <= tol["mask_px_frac"] * gz["n_valid"]
    assert record["depth_valid_bbox"] == golden["depth_valid_bbox"]
    assert abs(record["ground"]["drawn_row"] - golden["ground"]["drawn_row"]) <= tol["rows_px"]
    assert record["ground"]["badge"] == golden["ground"]["badge"]


def test_golden_frame_is_bit_identical_to_the_parent_capture(golden_pair: FramePair):
    if not (REFERENCE_DIR / "rgb.png").is_file():
        pytest.skip(f"parent reference capture not present: {REFERENCE_DIR}")
    stored = fsio.read_image(REFERENCE_DIR / "rgb.png")
    assert np.array_equal(np.ascontiguousarray(stored[..., ::-1]), golden_pair.bgr)
    assert np.array_equal(fsio.read_npy(REFERENCE_DIR / "depth.npy"), golden_pair.depth_m)
    identity = json.loads((REFERENCE_DIR / "record.json").read_text(encoding="utf-8"))
    identity = identity["frame_identity"]
    assert identity["bag_frame_no"] == GOLDEN_READ_INDEX
    assert golden_pair.color_timestamp_ms / 1000.0 == pytest.approx(
        identity["bag_time_sec"], abs=1e-6
    )


