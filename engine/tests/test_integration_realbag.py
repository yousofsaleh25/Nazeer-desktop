def _sha(array: np.ndarray) -> str:
    return hashlib.sha256(np.ascontiguousarray(array).tobytes()).hexdigest()


def _read_pair(bag: Path, read_index: int) -> FramePair:
    """Walk to one read index; only indices 0 and ``read_index`` are aligned (C2.1)."""
    walk = walk_bag(bag, sample_every=max(1, read_index))
    try:
        for pair in walk:
            if pair.read_index == read_index:
                return pair
    finally:
        walk.close()
    raise AssertionError(f"read index {read_index} not reached: {walk.summary.to_dict()}")


