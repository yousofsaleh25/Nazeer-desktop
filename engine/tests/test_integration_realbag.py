def _wait_job(client: TestClient, job_id: str, timeout: float) -> dict[str, Any]:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        snap = client.get(f"/candidates/jobs/{job_id}").json()
        if snap["terminal"]:
            return snap
        time.sleep(0.25)
    raise AssertionError(f"job {job_id} still running after {timeout} s")


def _check_candidate_set(grid: dict[str, Any]) -> None:
    """Contract C2 on real data: every gate, every reason, lowest depth MSE per 1.5 s bin."""
    walk, params, frames, cands = grid["walk"], grid["params"], grid["frames"], grid["candidates"]
    assert walk["walk_complete"] and walk["end_reason"] == "eof" and walk["n_incomplete"] == 0
    assert walk["path_fallback"] is None
    every = grid["sample_every_effective"]
    assert walk["n_pairs"] >= 760 and every == 5
    assert walk["n_sampled"] == len(frames) == math.ceil(walk["n_pairs"] / every)
    for f in frames:
        assert f["read_index"] % every == 0
        assert f["passed"] == (not f["rejection_reasons"]), f  # every rejection says why
    assert sum(grid["rejected_by_reason"].values()) == sum(
        len(f["rejection_reasons"]) for f in frames
    )
    assert 1 <= len(cands) <= params["m"] and grid["presentation"] == "unordered"
    for c in cands:  # the operator's hard gates (C2.4)
        assert c["passed"] and c["complete"] and c["conf"] >= params["conf"]
        assert c["z_mean"] >= 1.0 and c["z_median"] >= params["z_median_min_m"]
        assert params["maf_low"] <= c["mask_area_frac"] <= params["maf_high"]
        assert c["valid_frac"] >= params["valid_frac_min"]

    def bin_of(f: dict[str, Any]) -> int:
        return math.floor(f["read_index"] / walk["fps"] / params["bin_sec"])

    holders: dict[int, dict[str, Any]] = {}
    for f in sorted((f for f in frames if f["passed"]), key=lambda f: f["read_index"]):
        b = bin_of(f)
        if b not in holders or f["z_var"] < holders[b]["z_var"]:
            holders[b] = f
    for c in cands:  # each is the steadiest passing frame of its bin
        assert holders[bin_of(c)]["read_index"] == c["read_index"]

    def t(f: dict[str, Any]) -> float:
        return f["read_index"] / walk["fps"]

    gap = params["bin_sec"]
    for i, a in enumerate(cands):  # 1.5 s temporal diversity, also across bin edges
        assert all(abs(t(a) - t(b)) >= gap for b in cands[i + 1 :]), a["candidate_id"]
    chosen = {c["read_index"] for c in cands}
    skipped = grid["selection"]["skipped_too_close"]
    if len(holders) <= params["m"]:  # every holder is proposed or explained by the gap
        assert len(cands) + skipped == len(holders), (len(cands), skipped, len(holders))
    for bucket in ("SIDE", "END", "QUARTER"):
        picked = [
            h["z_var"]
            for h in holders.values()
            if h["bucket"] == bucket and h["read_index"] in chosen
        ]  # noqa: E501
        if not picked:
            continue
        for h in holders.values():  # a steadier frame of the same view left out: only the gap
            if h["bucket"] == bucket and h["read_index"] not in chosen and h["z_var"] < max(picked):
                assert any(abs(t(h) - t(c)) < gap for c in cands), (bucket, h["read_index"])


def _longest_run(values: np.ndarray) -> tuple[int, int]:
    padded = np.concatenate([[0], values.astype(np.int8), [0]])
    edges = np.flatnonzero(np.diff(padded))
    starts, ends = edges[0::2], edges[1::2] - 1
    i = int(np.argmax(ends - starts))
    return int(starts[i]), int(ends[i])


def _measurements(mask: np.ndarray, ground_row: int) -> tuple[list[dict[str, Any]], dict]:
    """Operator-like clicks placed from the real mask: height, body length (2D + 3D), back
    curve (2D + 3D) and two angles."""
    rows = np.flatnonzero(mask.any(axis=1))
    top = int(rows[0])
    u_top = float(np.median(np.flatnonzero(mask[top])))
    mid = int(top + 0.40 * (ground_row - top))
    a, b = _longest_run(mask[mid])
    left, right = float(a + 6), float(b - 6)
    back = []
    for c in np.linspace(a + 0.2 * (b - a), a + 0.8 * (b - a), 5):
        col = int(round(c))
        back.append([float(col), float(np.flatnonzero(mask[:, col])[0] + 4)])
    # above the broad back (not a thin head tip the 2-px erosion may remove entirely)
    back_col, back_top = back[2][0], back[2][1] - 4
    items = [
        {
            "id": 1,
            "kind": "distance_2d",
            "name": "ارتفاع الجمل",
            "points": [[u_top, top], [u_top, ground_row]],
        },
        {
            "id": 2,
            "kind": "distance_3d",
            "name": "طول الجسم",
            "points": [[left, mid], [right, mid]],
        },
        {
            "id": 3,
            "kind": "distance_2d",
            "name": "Body length 2D",
            "points": [[left, mid], [right, mid]],
        },
        {"id": 4, "kind": "curve_3d", "name": "منحنى الظهر", "points": back},
        {"id": 5, "kind": "curve_2d", "name": "Back polyline 2D", "points": back},
        {"id": 6, "kind": "angle_4point", "name": "زاوية قائمة", "line_a_id": 1, "line_b_id": 3},
        {
            "id": 7,
            "kind": "angle_3d_3point",
            "name": "Back angle 3D",
            "points": [back[0], back[2], back[4]],
        },
    ]
    at = {"top": top, "u_top": u_top, "mid": mid, "left": left, "right": right}
    at.update({"back_col": back_col, "back_top": back_top})
    return items, at


def test_bag_to_pdf_through_the_api_under_arabic_paths(segmenter, tmp_path: Path):
    if not SMALL_BAG.is_file():
        pytest.skip(f"realbag: {SMALL_BAG} not present")
    link_dir = PROJECT_DIR / "runs" / "اختبار"
    link_dir.mkdir(parents=True, exist_ok=True)
    bag = link_dir / SMALL_BAG.name
    made_link = False
    if not bag.exists():
        try:
            os.link(SMALL_BAG, bag)  # a hard link on the same volume, never a 2.8 GB copy
            made_link = True
        except OSError as exc:
            pytest.skip(f"cannot hard-link the bag under an Arabic folder: {exc}")
    root = tmp_path / "بيانات" / "nazeer"
    root.mkdir(parents=True)
    state = build_state(Settings(data_root=root, model_path=MODEL_PATH), segmenter=segmenter)
    try:
        with TestClient(create_app(state)) as client:
            _flow(client, bag, tmp_path)
    finally:
        if made_link:
            try:
                bag.unlink()
            except OSError:
                pass


def _flow(client: TestClient, bag: Path, tmp_path: Path) -> None:
    timings: dict[str, float] = {}

    # 1. open the bag: librealsense reads the Arabic path directly
    info = client.post("/bags/inspect", json={"path": str(bag)}).json()
    assert info["path_fallback"] is None and info["color"]["format"] == "format.rgb8"
    assert info["sample_every_effective"] == 5

    # 2. candidates: the real walk + model within the laptop budget
    t0 = time.monotonic()
    start = client.post("/candidates/jobs", json={"bag_path": str(bag)})
    assert start.status_code == 202, start.text
    job = _wait_job(client, start.json()["job"]["job_id"], timeout=600)
    timings["candidates_s"] = time.monotonic() - t0
    assert job["state"] == "done", job
    assert timings["candidates_s"] < CANDIDATE_BUDGET_S, timings
    url = f"/candidates/{job['result']['fingerprint']}/{job['result']['params_hash']}"
    grid = client.get(url, params={"include_frames": True}).json()
    _check_candidate_set(grid)
    cands = grid["candidates"]
    cand = next((c for c in cands if c["bucket"] == "SIDE"), cands[0])
    thumb = client.get(cand["urls"]["thumb"])
    assert thumb.status_code == 200 and thumb.headers["content-type"] == "image/jpeg"

    # 3. a session on the chosen frame; Z_ref is the candidate's eroded-mask median
    created = client.post(
        "/sessions", json={"candidate": cand["ref"], "camel_id": "جمل-004", "operator": "المشغل"}
    )
    assert created.status_code == 201, created.text
    view = created.json()
    sid, frame = view["session_id"], view["frame"]
    assert frame["z_ref"]["statistic"] == "median"
    assert frame["z_ref"]["z_ref_m"] == pytest.approx(cand["z_median"], abs=1e-6)
    assert frame["bag"]["read_index"] == cand["read_index"]
    mask_png = client.get(frame["assets"]["mask"]).content
    mask = fsio.decode_image(mask_png, flags=cv2.IMREAD_GRAYSCALE) != 0
    height, width = mask.shape
    ground_row = int(frame["ground"]["drawn_row"])
    items, at = _measurements(mask, ground_row)

    # depth probes: inside the body, just above the silhouette, on the ground below it
    inside = client.post(
        f"/sessions/{sid}/depth", json={"u": (at["left"] + at["right"]) / 2, "v": at["mid"]}
    ).json()
    assert inside["ok"] and inside["inside_mask"]
    assert inside["source"] in ("window_median", "knn_fill")
    above = client.post(
        f"/sessions/{sid}/depth", json={"u": at["back_col"], "v": at["back_top"] - 15, "seq": 2}
    ).json()
    assert above["seq"] == 2 and not above["inside_mask"] and above["nn_dist_px_max"] >= 15
    # snapped to the camel; named for the depth-less band when the click sits in it (C1.4)
    expected = "knn_snapped_to_mask" if above["inside_depth_bbox"] else "knn_no_depth_band"
    assert above["source"] == expected, above
    assert above["nn_dist_m_max"] > 0 and "snapped to camel" in above["basis"]["en"]
    v_ground = min(height - 1, ground_row + 15)
    if not mask[v_ground, int(round(at["u_top"]))]:
        ground = client.post(
            f"/sessions/{sid}/depth",
            json={"u": at["u_top"], "v": v_ground, "target": "ground"},
        ).json()
        assert ground["target"] == "ground"
        assert (
            ground["source"] == "direct_off_mask" or "ground_target_unresolved" in ground["flags"]
        )

    # 4. measure and autosave: every value computed by the engine, no NaN on the wire
    saved = client.put(
        f"/sessions/{sid}/document",
        json={"revision": 1, "camel_id": "جمل-004", "operator": "المشغل", "measurements": items},
    )
    assert saved.status_code == 200, saved.text
    doc = jsonsafe.loads_strict(saved.content)
    rows = {m["id"]: m for m in doc["measurements"]}
    assert doc["summary"]["n_measurements"] == 7
    camel_height = rows[1]["presentation"]["value"]
    assert 1.2 <= camel_height <= 3.2, camel_height  # metres: intrinsics + depth units wired
    l3, l2 = rows[2]["presentation"]["value"], rows[3]["presentation"]["value"]
    assert l3 is not None and l2 is not None and 0.6 <= l3 / l2 <= 1.7, (l3, l2)
    assert rows[2]["p1_depth"]["source"] and rows[2]["p2_depth"]["source"]
    curve = rows[4]
    assert curve["kind"] == "curve_3d" and curve["n_points"] == 5
    assert len(curve["segment_lengths_m"]) == 4 and len(curve["point_depth"]) == 5
    assert curve["n_direct"] + curve["n_knn"] == 5
    assert all(
        p["source"] for p in curve["point_depth"]
    )  # each point says where its depth came from
    assert curve["cross_check_2d_m"] == pytest.approx(rows[5]["presentation"]["value"], rel=1e-9)
    assert rows[6]["kind"] == "angle_2d_4point"
    assert abs(rows[6]["presentation"]["value"] - 90.0) < 0.5  # vertical vs horizontal line
    assert rows[7]["kind"] == "angle_3d_3point"
    assert rows[7]["presentation"]["value"] is not None or rows[7]["rejection_reason"]

    # 5. finalize: the engine renders the overlay once; the PNG is the approval surface
    t0 = time.monotonic()
    sealed = client.post(
        f"/sessions/{sid}/finalize",
        json={
            "revision": 1,
            "report_inputs": {
                "language": "both",
                "names": {"judge": "الحكم", "event": "مزاين الإبل"},
            },
        },
    )
    timings["finalize_s"] = time.monotonic() - t0
    assert sealed.status_code == 200, sealed.text
    view = sealed.json()
    overlay = view["outputs"]["overlay"]
    png = client.get(overlay["url"]).content
    assert hashlib.sha256(png).hexdigest() == overlay["sha256"]
    assert (overlay["width"], overlay["height"]) == (width, height + 120)

    # 6. print (headless Edge = Electron's Chromium printer) and seal the PDF
    names = [m["name"] for m in view["measurements"]]
    table = [(m["name"], m["presentation"]["value_text"]["en"]) for m in view["measurements"]]
    # like the app's print page: camel id and the judge / council / event wells are printed too
    wells = [v for v in view["report_inputs"]["names"].values() if v]
    title = " — ".join(["تقرير قياس", view["camel_id"], *wells])
    assert set(view["required_report_texts"]) == {*names, *wells, view["camel_id"]}
    t0 = time.monotonic()
    printed = print_to_pdf(report_page(png, table, title=title), tmp_path / "print")
    timings["print_s"] = time.monotonic() - t0
    strict = printed is not None
    if printed is None:  # no Edge on this machine: an image-exact PDF without the font checks
        rgb = fsio.decode_image(png)[..., ::-1]
        printed = build_pdf(image_rgb=np.ascontiguousarray(rgb), texts=["Body length 2D"])
    upload = client.post(
        f"/sessions/{sid}/report",
        params={"require_text": strict, "require_font": strict},
        content=printed,
        headers={
            "Content-Type": "application/pdf",
            "X-Overlay-Sha256": overlay["sha256"],
            "X-Overlay-Version": str(overlay["version"]),
            "X-Report-Model-Sha256": view["outputs"]["report_model"]["sha256"],
        },
    )
    assert upload.status_code == 200, upload.text
    probe = upload.json()["probe"]
    assert probe["verdict"] == "PASS" and probe["attachments_ok"], probe
    assert probe["pixel"]["match"]["max_abs_diff"] == 0
